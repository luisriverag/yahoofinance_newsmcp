"""MCP server exposing morning Yahoo Finance news digests as tools.

Run with ``yahoofinance-newsmcp-server``. Defaults to stdio transport (a client
spawns this as a subprocess and drives it directly) for local/single-host use;
set ``YF_MCP_TRANSPORT=http`` to instead serve MCP over Streamable HTTP as an
always-on service — the way to reach this server from a client running on a
different host or container, and the only mode in which the built-in morning
scheduler runs. See this project's README for both modes.
"""

from __future__ import annotations

import functools
import hmac
import logging
import os
import sys
from typing import List, Optional

from mcp.server.mcpserver import MCPServer
from mcp.server.mcpserver.exceptions import ToolError
from starlette.responses import JSONResponse
from starlette.types import ASGIApp, Receive, Scope, Send

from . import health, redaction
from .config import Settings, configure_logging, get_settings
from .digest import DigestError, load_latest, render_markdown
from .llm import LlmClient, LlmError
from .services import deliver_digest, generate_and_persist
from .summarize import summarize_articles, summarize_company
from .telegram import TelegramError
from .yahoo import NewsArticle, YahooError, YahooFinanceClient

logger = logging.getLogger("yahoofinance-newsmcp")

# Anticipated, "the requested operation failed" errors (missing config,
# unreachable upstream, empty watchlist, ...) are re-raised as ToolError so the
# client gets a normal tool result it can react to, instead of a protocol-level
# crash. Anything else (a real bug) is left to propagate as-is.
_EXPECTED_ERRORS = (
    YahooError,
    LlmError,
    TelegramError,
    DigestError,
    FileNotFoundError,
    FileExistsError,
    ValueError,
    KeyError,
    PermissionError,
)

mcp = MCPServer(
    "yahoofinance-newsmcp",
    instructions=(
        "Tools for a Yahoo Finance morning news digest. The watchlist is "
        "configured server-side (WATCHLIST_TICKERS/WATCHLIST_FILE); call "
        "list_watchlist first if you don't know it. Use fetch_news for raw "
        "headlines about one ticker, summarize_ticker for that ticker's "
        "per-article and company summaries, and generate_digest for the full "
        "watchlist briefing (per-article, per-company, and overall). "
        "send_digest additionally delivers the digest to the configured "
        "Telegram chat. The summaries are produced server-side by the "
        "configured model and are neutral/factual, never investment advice."
    ),
)


def _tool(fn):
    @functools.wraps(fn)
    def wrapper(*args, **kwargs):
        logger.info("Tool %r called (%s)", fn.__name__, redaction.redact_text(repr(kwargs)))
        try:
            result = fn(*args, **kwargs)
        except _EXPECTED_ERRORS as exc:
            safe_detail = redaction.redact_text(str(exc))
            logger.warning("Tool %r failed: %s: %s", fn.__name__, type(exc).__name__, safe_detail)
            raise ToolError(safe_detail) from exc
        logger.info("Tool %r succeeded", fn.__name__)
        return result

    return mcp.tool()(wrapper)


def _article_dict(article: NewsArticle, *, include_body: bool = False) -> dict:
    data = {
        "ticker": article.ticker,
        "title": article.title,
        "link": article.link,
        "publisher": article.publisher,
        "published_at": article.published_at.isoformat() if article.published_at else None,
        "snippet": article.snippet,
    }
    if include_body:
        data["body"] = article.body
    return data


@_tool
def list_watchlist() -> List[str]:
    """List the tickers the server is configured to cover each morning."""

    return get_settings().resolved_tickers()


@_tool
def fetch_news(ticker: str, limit: Optional[int] = None) -> List[dict]:
    """Fetch recent Yahoo Finance news for one ticker (no summarization).

    Use this for raw headlines and links. ``limit`` defaults to
    NEWS_PER_TICKER; only articles within NEWS_LOOKBACK_HOURS are returned.
    """

    settings = get_settings()
    with YahooFinanceClient(settings) as client:
        articles = client.fetch_news(ticker, limit=limit)
    return [_article_dict(article) for article in articles]


@_tool
def summarize_ticker(ticker: str, limit: Optional[int] = None) -> dict:
    """Summarize today's news for one ticker: a company paragraph plus a
    one-to-two sentence summary per article, generated by the configured model.
    """

    settings = get_settings()
    with YahooFinanceClient(settings) as client:
        articles = client.enrich(client.fetch_news(ticker, limit=limit))
    if not articles:
        return {"ticker": ticker.upper(), "overall_summary": "No recent news.", "articles": []}

    with LlmClient(settings) as llm:
        summaries = summarize_articles(llm, ticker, articles)
        overall = summarize_company(llm, ticker, articles)

    return {
        "ticker": ticker.upper(),
        "overall_summary": overall,
        "articles": [
            {
                **_article_dict(article),
                "summary": summaries[index] if index < len(summaries) else article.title,
            }
            for index, article in enumerate(articles)
        ],
    }


@_tool
def generate_digest() -> dict:
    """Generate the full watchlist digest: per-article, per-company, and overall
    summaries. Persists the result when DIGEST_STATE_DIR is configured, and
    returns both the structured digest and the rendered Markdown.
    """

    settings = get_settings()
    digest = generate_and_persist(settings)
    return {"digest": _digest_dict(digest), "markdown": render_markdown(digest)}


@_tool
def send_digest(chat_id: Optional[str] = None) -> dict:
    """Generate the digest and deliver it to Telegram.

    ``chat_id`` overrides TELEGRAM_CHAT_ID. Requires TELEGRAM_BOT_TOKEN and a
    chat id. Returns the rendered Markdown and the message ids sent.
    """

    settings = get_settings()
    digest = generate_and_persist(settings)
    message_ids = deliver_digest(digest, settings, chat_id=chat_id)
    return {
        "digest": _digest_dict(digest),
        "markdown": render_markdown(digest),
        "message_ids": message_ids,
    }


@_tool
def get_last_digest() -> dict:
    """Return the most recently persisted digest (Markdown + structure), if any."""

    from .config import get_settings as _get_settings

    digest = load_latest(_get_settings().digest_state_dir)
    if digest is None:
        return {"available": False, "markdown": "", "digest": None}
    return {"available": True, "markdown": render_markdown(digest), "digest": _digest_dict(digest)}


@_tool
def check_health() -> dict:
    """Report whether the watchlist, Yahoo Finance, the summarization model,
    Telegram delivery, and digest persistence are configured and reachable.
    """

    report = health.check_health(get_settings())
    return {
        "healthy": report.healthy,
        "checks": [
            {"name": c.name, "ok": c.ok, "detail": c.detail, "required": c.required}
            for c in report.checks
        ],
    }


def _digest_dict(digest) -> dict:
    return {
        "generated_at": digest.generated_at,
        "lookback_hours": digest.lookback_hours,
        "overall_summary": digest.overall_summary,
        "total_articles": digest.total_articles,
        "companies": [
            {
                "ticker": company.ticker,
                "article_count": company.article_count,
                "overall_summary": company.overall_summary,
                "articles": [
                    {
                        "title": article.title,
                        "link": article.link,
                        "publisher": article.publisher,
                        "published_at": article.published_at,
                        "summary": article.summary,
                    }
                    for article in company.articles
                ],
            }
            for company in digest.companies
        ],
    }


class _BearerAuthMiddleware:
    """Rejects any HTTP request without a matching ``Authorization: Bearer
    <token>`` header before it reaches the MCP app. Constant-time compare to
    avoid a timing side-channel on the token check."""

    def __init__(self, app: ASGIApp, token: str) -> None:
        self._app = app
        self._expected = f"Bearer {token}"

    async def __call__(self, scope: Scope, receive: Receive, send: Send) -> None:
        if scope["type"] != "http":
            await self._app(scope, receive, send)
            return

        headers = dict(scope.get("headers") or [])
        provided = headers.get(b"authorization", b"").decode("latin-1")
        if not hmac.compare_digest(provided, self._expected):
            response = JSONResponse({"error": "unauthorized"}, status_code=401)
            await response(scope, receive, send)
            return

        await self._app(scope, receive, send)


def _morning_callback(settings: Settings) -> None:
    logger.info("Morning digest run starting.")
    run = run_morning_digest_safe(settings)
    if run is not None:
        logger.info("Morning digest delivered: %d message(s).", len(run.message_ids))


def run_morning_digest_safe(settings: Settings):
    from .services import run_morning_digest

    try:
        return run_morning_digest(settings)
    except _EXPECTED_ERRORS as exc:
        logger.error("Morning digest failed: %s: %s", type(exc).__name__, redaction.redact_text(str(exc)))
        return None


def main() -> None:
    settings = get_settings()
    configure_logging(settings)
    transport = os.getenv("YF_MCP_TRANSPORT", "stdio").strip().lower()

    if transport in ("", "stdio"):
        if settings.digest_scheduler_enabled:
            print(
                "WARNING: DIGEST_SCHEDULER_ENABLED=true has no effect in stdio "
                "transport (the process is spawned per client request and "
                "blocks on the client). Use YF_MCP_TRANSPORT=http for the "
                "morning scheduler.",
                file=sys.stderr,
            )
        mcp.run()
        return

    if transport not in ("http", "streamable-http"):
        raise ValueError(f"Unknown YF_MCP_TRANSPORT={transport!r}; expected 'stdio' or 'http'.")

    import uvicorn

    from .scheduler import MorningScheduler

    host = os.getenv("YF_MCP_HTTP_HOST", "0.0.0.0")
    port = int(os.getenv("YF_MCP_HTTP_PORT", "8080"))
    path = os.getenv("YF_MCP_HTTP_PATH", "/mcp")
    token = os.getenv("YF_MCP_AUTH_TOKEN", "").strip()

    scheduler: Optional[MorningScheduler] = None
    if settings.digest_scheduler_enabled:
        scheduler = MorningScheduler(
            settings.digest_time,
            settings.digest_timezone,
            lambda: _morning_callback(settings),
        )
        scheduler.start()

    app = mcp.streamable_http_app(streamable_http_path=path, host=host)
    if token:
        app = _BearerAuthMiddleware(app, token)
    else:
        print(
            "WARNING: YF_MCP_AUTH_TOKEN is not set. This MCP HTTP endpoint has "
            "no authentication — anyone who can reach it can read your "
            "watchlist, trigger digest generation (which calls your "
            "summarization model), and send messages to your Telegram chat. "
            "Set YF_MCP_AUTH_TOKEN unless the network path here is otherwise "
            "fully trusted.",
            file=sys.stderr,
        )

    try:
        uvicorn.run(app, host=host, port=port, log_level=settings.log_level.lower())
    finally:
        if scheduler is not None:
            scheduler.stop()


if __name__ == "__main__":
    main()
